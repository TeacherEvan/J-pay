import puppeteer from "puppeteer-core";
const b = await puppeteer.connect({ browserURL: "http://127.0.0.1:9300", defaultViewport: null, protocolTimeout: 90000 });
const pages = await b.pages();
const p = pages.find(pg => pg.url().includes("/moderator"));
p.on("console", m => { if (m.type() === "error") console.log("CONSOLE:", m.text().slice(0, 300)); });
await p.reload({ waitUntil: "networkidle2" });
await new Promise(r => setTimeout(r, 3500));
const hasBtn = await p.evaluate(() => { const btn=[...document.querySelectorAll("button")].find(x=>x.textContent.includes("Seed investor demo")); if(btn){btn.click();return true;} return false; });
console.log("btn:", hasBtn);
await new Promise(r => setTimeout(r, 20000));
console.log("msg:", await p.evaluate(() => [...document.querySelectorAll("span,div")].map(x => x.textContent).find(t => t && (t.includes("Seeded") || t.includes("failed")))));
await b.disconnect(); process.exit(0);
